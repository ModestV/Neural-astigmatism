"""Стабильная палитра по legend_id. Задача T4."""

from __future__ import annotations

import re
import zlib

# Палитра из 24 насыщенных цветов, различимых на белом фоне (серых нет: серый занят фоном).
# Порядок подобран так, чтобы соседние индексы заметно различались по тону.
PALETTE: tuple[tuple[int, int, int], ...] = (
    (230, 25, 75),  # красный
    (0, 130, 200),  # синий
    (60, 180, 75),  # зеленый
    (245, 130, 48),  # оранжевый
    (145, 30, 180),  # фиолетовый
    (0, 128, 128),  # бирюзовый
    (240, 50, 230),  # маджента
    (154, 99, 36),  # коричневый
    (66, 212, 244),  # голубой
    (128, 0, 0),  # бордовый
    (170, 190, 0),  # лаймовый
    (0, 0, 117),  # темно-синий
    (255, 105, 180),  # розовый
    (0, 168, 107),  # нефритовый
    (184, 134, 11),  # горчичный
    (106, 61, 154),  # индиго
    (90, 60, 200),  # сине-фиолетовый
    (0, 100, 60),  # темно-зеленый
    (128, 128, 0),  # оливковый
    (255, 69, 0),  # красно-оранжевый
    (23, 190, 207),  # циан
    (120, 200, 140),  # мятный
    (200, 110, 150),  # пыльная роза
    (200, 0, 120),  # пурпурный
)

# Шаг по палитре для соседних номеров (взаимно прост с len(PALETTE) = 24).
_NUM_STEP = 7
_TRAILING_NUM = re.compile(r"^(.*?)(\d{1,9})$", re.DOTALL)


def color_for(legend_id: str) -> tuple[int, int, int]:
    """Различимый RGB (0..255), детерминированный по ``legend_id`` (не зависит от порядка
    эталонов и от PYTHONHASHSEED).

    Индекс = crc32 префикса + номер * шаг: последовательные ``sym1``, ``sym2``, ... получают
    разные цвета (до длины палитры), остальные идентификаторы распределяются по crc32.
    """
    m = _TRAILING_NUM.match(legend_id)
    if m:
        prefix, num = m.group(1), int(m.group(2))
    else:
        prefix, num = legend_id, 0
    idx = (zlib.crc32(prefix.encode("utf-8")) + num * _NUM_STEP) % len(PALETTE)
    return PALETTE[idx]


def color_hex(legend_id: str) -> str:
    """Цвет класса в виде ``#rrggbb``."""
    r, g, b = color_for(legend_id)
    return f"#{r:02x}{g:02x}{b:02x}"
